use App\Support\Petshop;
use Carbon\Carbon;

function toko(string $k): string
{
    return Petshop::get($k);
}

function rp($n): string
{
    return 'Rp' . number_format((int) $n, 0, ',', '.');
}

/** 2026-10-28 → 28 Oktober 2026 */
function tgl($t, bool $jam = false): string
{
    if (! $t) {
        return '-';
    }
    $c = $t instanceof \DateTimeInterface ? Carbon::instance($t) : Carbon::parse($t);
    $b = [1 => 'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni', 'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'];
    return $c->day . ' ' . $b[$c->month] . ' ' . $c->year . ($jam ? ', ' . $c->format('H.i') : '');
}

function lencana(string $teks, string $warna = 'abu'): string
{
    return '<span class="lencana ' . e($warna) . '">' . e($teks) . '</span>';
}

